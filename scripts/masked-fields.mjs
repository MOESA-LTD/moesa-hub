// Writes two files from public.field_class:
// - app/src/@types/maskedFields.generated.ts: the fields each `api` view may return as null: the
//   sensitive fields of every table, plus every column of a shared table (a provider row shared
//   with a client tenant) that is not client_visible. The app types those fields nullable from it
//   (app/src/@types/database.ts).
// - app/src/constants/clientVisible.ts: the client_visible fields per shared table, plus the
//   derived client_status; the app's single source of what a client reads (F11).
// Run by `pnpm dev:supabase-types`; `--check` only compares the committed files with the database
// (see masked-fields.test.mjs).
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { psql, ROOT } from './seed-story.mjs';

export const OUTPUT = path.join(ROOT, 'app', 'src', '@types', 'maskedFields.generated.ts');

export const CLIENT_VISIBLE_OUTPUT = path.join(ROOT, 'app', 'src', 'constants', 'clientVisible.ts');

// Sensitive fields, and the columns of a shared table that are not client_visible: a client reads
// NULL there. The derived client_status is no column of the table, so it is never listed.
export const SENSITIVE_SQL = `
SELECT replace(resource_name, 'public.', '') || '|' || field FROM public.field_class WHERE class = 'sensitive'
UNION
SELECT c.relname || '|' || a.attname
FROM pg_catalog.pg_class c
JOIN pg_catalog.pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
WHERE c.relnamespace = 'public'::regnamespace AND c.relkind = 'r' AND private.is_shared_table(c.relname::TEXT)
  AND NOT coalesce((SELECT f.client_visible FROM public.field_class f
                    WHERE f.resource_name = 'public.' || c.relname AND f.field = a.attname), FALSE)
ORDER BY 1;`;

export const CLIENT_VISIBLE_SQL =
   "SELECT replace(resource_name, 'public.', '') || '|' || field FROM public.field_class WHERE client_visible ORDER BY 1;";

/** "table|field" lines into sorted [table, field] pairs. */
export const parseRows = (output) =>
   output
      .split(/\r?\n/)
      .filter(Boolean)
      .map((line) => line.split('|'))
      .sort(([a, x], [b, y]) => a.localeCompare(b) || x.localeCompare(y));

const group = (pairs) => {
   const tables = new Map();
   for (const [table, field] of pairs) tables.set(table, [...(tables.get(table) ?? []), field]);
   return [...tables].map(([table, fields]) => `   ${table}: [${fields.map((field) => `'${field}'`).join(', ')}]`);
};

/** The TypeScript source of the client-visible constants. */
export const renderClientVisible = (pairs) =>
   [
      '// Generated by scripts/masked-fields.mjs from public.field_class (client_visible), plus the derived',
      '// client_status. Do not edit: run `pnpm dev:supabase-types` after a change of the classification.',
      '// The fields of each shared table a client tenant reads; every other column reads NULL for it.',
      'export const CLIENT_VISIBLE_FIELDS = {',
      group(pairs).join(',\n'),
      '} as const;',
      ''
   ].join('\n');

/** The TypeScript source for the pairs. */
export function render(pairs) {
   const entries = group(pairs);
   return [
      '// Generated by scripts/masked-fields.mjs from public.field_class (sensitive, and not client_visible on a shared table). Do not edit:',
      '// run `pnpm dev:supabase-types` after a change of the classification.',
      'export const MASKED_FIELDS = {',
      entries.join(',\n'),
      '} as const;',
      ''
   ].join('\n');
}

/** The [table, field] pairs a generated file lists, however it was formatted. */
export function parseGenerated(source) {
   const body = source.slice(source.indexOf('{') + 1, source.lastIndexOf('}'));
   const pairs = [];
   for (const [, table, list] of body.matchAll(/(\w+):\s*\[([^\]]*)\]/g)) {
      for (const [, field] of list.matchAll(/'(\w+)'/g)) pairs.push([table, field]);
   }
   return pairs.sort(([a, x], [b, y]) => a.localeCompare(b) || x.localeCompare(y));
}

export const fetchPairs = (sql = psql) => parseRows(sql(SENSITIVE_SQL));

/** The client_visible fields, plus the derived client_status (a field_class row, 067). */
export const fetchClientVisible = (sql = psql) => parseRows(sql(CLIENT_VISIBLE_SQL));

function main() {
   const pairs = fetchPairs();
   if (!pairs.length) throw new Error('public.field_class lists no sensitive field');
   const visible = fetchClientVisible();
   if (process.argv.includes('--check')) {
      for (const [file, expected] of [[OUTPUT, pairs], [CLIENT_VISIBLE_OUTPUT, visible]]) {
         if (JSON.stringify(parseGenerated(readFileSync(file, 'utf8'))) !== JSON.stringify(expected)) {
            console.error(`masked-fields: ${path.basename(file)} differs from public.field_class`);
            process.exit(1);
         }
      }
      return;
   }
   writeFileSync(OUTPUT, render(pairs));
   writeFileSync(CLIENT_VISIBLE_OUTPUT, renderClientVisible(visible));
   // In the app's own style, so the committed files stay as written.
   spawnSync('npx', ['prettier', '--write', OUTPUT, CLIENT_VISIBLE_OUTPUT], {
      cwd: path.join(ROOT, 'app'),
      shell: process.platform === 'win32'
   });
   console.log(`masked-fields: ${pairs.length} fields`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
   try {
      main();
   } catch (error) {
      console.error(`masked-fields: ${error.message}`);
      process.exit(1);
   }
}
